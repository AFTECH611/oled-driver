// ============================================================================
//  Constructor / Init
// ============================================================================
OledDriver::OledDriver(std::unique_ptr<I2CDevice> i2c)
    : i2c_(std::move(i2c)) {}

bool OledDriver::init() {
    if (!i2c_ || !i2c_->isOpen()) return false;

    // SSD1306 128×64 initialisation sequence
    return sendCmds({
        0xAE,       // display off
        0xD5, 0x80, // clock divide / oscillator frequency
        0xA8, 0x3F, // multiplex ratio (64-1)
        0xD3, 0x00, // display offset = 0
        0x40,       // display start line = 0
        0x8D, 0x14, // charge pump ON
        0x20, 0x00, // horizontal addressing mode
        0xA1,       // segment re-map (col 127 → SEG0)
        0xC8,       // COM scan direction remapped
        0xDA, 0x12, // COM pins hardware config
        0x81, 0xCF, // contrast
        0xD9, 0xF1, // pre-charge period
        0xDB, 0x40, // VCOMH deselect level
        0xA4,       // output follows RAM
        0xA6,       // normal display (not inverted)
        0xAF,       // display ON
    });
}

// ============================================================================
//  Low-level I²C helpers
// ============================================================================
bool OledDriver::sendCmd(uint8_t cmd) {
    const uint8_t buf[2] = {0x00, cmd}; // control byte 0x00 = command
    return i2c_->write(buf);
}

bool OledDriver::sendCmds(std::initializer_list<uint8_t> cmds) {
    for (auto c : cmds)
        if (!sendCmd(c)) return false;
    return true;
}

bool OledDriver::sendData(std::span<const uint8_t> data) {
    // Prepend data-control byte 0x40
    std::vector<uint8_t> buf;
    buf.reserve(1 + data.size());
    buf.push_back(0x40);
    buf.insert(buf.end(), data.begin(), data.end());
    return i2c_->write(buf);
}

// ============================================================================
//  Framebuffer ops
// ============================================================================
void OledDriver::clear(bool on) {
    buf_.fill(on ? 0xFF : 0x00);
}

void OledDriver::display() {
    sendCmds({0x21, 0x00, 0x7F});  // column address 0–127
    sendCmds({0x22, 0x00, 0x07});  // page address   0–7
    sendData(buf_);
}

// ============================================================================
//  Pixel
// ============================================================================
void OledDriver::setPixel(int x, int y, bool on) {
    if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT) return;
    const int idx = (y / 8) * WIDTH + x;
    const int bit = y % 8;
    if (on) buf_[idx] |=  static_cast<uint8_t>(1u << bit);
    else    buf_[idx] &= ~static_cast<uint8_t>(1u << bit);
}

bool OledDriver::getPixel(int x, int y) const {
    if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT) return false;
    return (buf_[(y / 8) * WIDTH + x] >> (y % 8)) & 1;
}

// ============================================================================
//  Lines & shapes
// ============================================================================
void OledDriver::drawHLine(int x, int y, int w, bool on) {
    for (int i = 0; i < w; ++i) setPixel(x + i, y, on);
}

void OledDriver::drawVLine(int x, int y, int h, bool on) {
    for (int i = 0; i < h; ++i) setPixel(x, y + i, on);
}

void OledDriver::drawLine(int x0, int y0, int x1, int y1, bool on) {
    // Bresenham
    int dx = std::abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    int dy = std::abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    int err = (dx > dy ? dx : -dy) / 2;
    for (;;) {
        setPixel(x0, y0, on);
        if (x0 == x1 && y0 == y1) break;
        int e2 = err;
        if (e2 > -dx) { err -= dy; x0 += sx; }
        if (e2 <  dy) { err += dx; y0 += sy; }
    }
}

void OledDriver::drawRect(int x, int y, int w, int h, bool on) {
    drawHLine(x,       y,       w, on);
    drawHLine(x,       y+h-1,   w, on);
    drawVLine(x,       y,       h, on);
    drawVLine(x+w-1,   y,       h, on);
}

void OledDriver::fillRect(int x, int y, int w, int h, bool on) {
    for (int row = 0; row < h; ++row)
        drawHLine(x, y + row, w, on);
}

void OledDriver::drawCircle(int cx, int cy, int r, bool on) {
    int x = 0, y = r, d = 3 - 2 * r;
    auto put8 = [&](int px, int py) {
        setPixel(cx+px, cy+py, on); setPixel(cx-px, cy+py, on);
        setPixel(cx+px, cy-py, on); setPixel(cx-px, cy-py, on);
        setPixel(cx+py, cy+px, on); setPixel(cx-py, cy+px, on);
        setPixel(cx+py, cy-px, on); setPixel(cx-py, cy-px, on);
    };
    while (y >= x) { put8(x, y); ++x; if (d > 0) { --y; d += 4*(x-y)+10; } else d += 4*x+6; }
}

void OledDriver::fillCircle(int cx, int cy, int r, bool on) {
    for (int y = -r; y <= r; ++y)
        for (int x = -r; x <= r; ++x)
            if (x*x + y*y <= r*r) setPixel(cx+x, cy+y, on);
}

// ============================================================================
//  Text
// ============================================================================
void OledDriver::drawChar(int x, int y, char c, bool on, uint8_t scale) {
    if (c < 0x20 || c > 0x7F) c = '?';
    const uint8_t* glyph = FONT_6x8[static_cast<uint8_t>(c) - 0x20];
    for (int col = 0; col < 6; ++col) {
        uint8_t coldata = glyph[col];
        for (int row = 0; row < 8; ++row) {
            if (coldata & (1u << row)) {
                if (scale == 1) {
                    setPixel(x + col, y + row, on);
                } else {
                    fillRect(x + col*scale, y + row*scale, scale, scale, on);
                }
            }
        }
    }
}

void OledDriver::drawString(int x, int y, std::string_view str,
                            bool on, uint8_t scale) {
    int cx = x;
    for (char c : str) {
        if (cx + FONT_W * scale > WIDTH) break;
        drawChar(cx, y, c, on, scale);
        cx += FONT_W * scale;
    }
}

int OledDriver::textWidth(std::string_view str, uint8_t scale) const {
    return static_cast<int>(str.size()) * FONT_W * scale;
}

// ============================================================================
//  Display control
// ============================================================================
void OledDriver::setSleep(bool sleep) {
    sendCmd(sleep ? 0xAE : 0xAF);
}

void OledDriver::setInvert(bool invert) {
    sendCmd(invert ? 0xA7 : 0xA6);
}

void OledDriver::setContrast(uint8_t contrast) {
    sendCmds({0x81, contrast});
}

// ============================================================================
//  Convenience: horizontal progress bar
// ============================================================================
void OledDriver::drawBar(int x, int y, int w, int h, int pct, bool on) {
    pct = std::clamp(pct, 0, 100);
    drawRect(x, y, w, h, on);
    const int fill = (pct * (w - 2)) / 100;
    if (fill > 0) fillRect(x + 1, y + 1, fill, h - 2, on);
}